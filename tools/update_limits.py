"""Generate the limit reference from the restricted constant catalog grammar.

The Rust documentation test compares every generated numeric value with its
compiled constant. This reader never evaluates Python or arbitrary Rust code.
"""
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def catalog(source):
    definitions = {}
    for group in re.finditer(r'(?ms)^pub mod (\w+) \{(.*?)^\}', source):
        for row in re.finditer(r'(?m)^\s*pub const (\w+): (usize|u64|u32|i64|f64) = ([^;]+);', group[2]):
            key = group[1] + '.' + row[1]
            if key in definitions:
                raise ValueError('Duplicate limit: ' + key)
            definitions[key] = (row[2], row[3])
    values, visiting = {}, set()

    def value(key):
        if key in values:
            return values[key]
        if key in visiting:
            raise ValueError('Cyclic limit expression: ' + key)
        visiting.add(key)
        kind, expression = definitions[key]
        expression = re.sub(r'\bas (?:usize|u64|u32|i64)\b', '', expression)
        expression = expression.replace('super::', '').replace('::', '.')
        tree = ast.parse(' '.join(expression.split()), mode='eval')

        def read(node):
            if isinstance(node, ast.Constant) and type(node.value) in (int, float):
                return node.value
            if isinstance(node, ast.Name):
                return value(key.rsplit('.', 1)[0] + '.' + node.id)
            if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
                return value(node.value.id + '.' + node.attr)
            if isinstance(node, ast.BinOp):
                a, b = read(node.left), read(node.right)
                if isinstance(node.op, ast.Add): return a + b
                if isinstance(node.op, ast.Sub): return a - b
                if isinstance(node.op, ast.Mult): return a * b
                if isinstance(node.op, ast.Div):
                    if type(a) is int and type(b) is int:
                        if a < 0 or b <= 0: raise ValueError('Unsupported signed division')
                        return a // b
                    return a / b
            raise ValueError('Unsupported limit expression: ' + key)

        result = read(tree.body)
        if kind == 'f64': result = float(result)
        elif type(result) is not int or result < 0:
            raise ValueError('Non-integer resource limit: ' + key)
        visiting.remove(key)
        values[key] = result
        return result

    return [(key, kind, value(key), ' '.join(expression.split()))
            for key, (kind, expression) in sorted(definitions.items())]


def report(source):
    rows = catalog(source)
    if not rows: raise ValueError('Empty resource limit catalog')
    lines = ['# Resource limits', '',
        'Generated by `python tools/update_limits.py` from [src/limits.rs](../src/limits.rs).',
        'The Rust documentation check compares every row with its compiled constant.', '',
        'These are current ceilings and bounded-evaluation settings, not promised workload sizes.',
        'A request must satisfy every applicable document, storage, work and memory budget.',
        'Equal values do not imply interchangeable policies. Existing public Rust module paths',
        're-export the central constants. No limit is raised by this consolidation.', '',
        'The native store tile-count ceiling remains independent of its pixel ceiling:',
        'partial edge blocks consume tile entries too. W4 target sizes remain future work.',
        'This first catalog consolidates named constants; the W0 audit of inline bounds,',
        'capability literals and diagnostic messages remains in progress.', '',
        '| Constant | Rust type | Value | Definition |',
        '| --- | --- | ---: | --- |']
    for key, kind, number, expression in rows:
        lines.append(f'| `{key}` | `{kind}` | {json.dumps(number)} | `{expression}` |')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    source = (ROOT/'src/limits.rs').read_text(encoding='utf-8')
    (ROOT/'docs/LIMITS.md').write_text(report(source), encoding='utf-8')
    print(f'Generated {len(catalog(source))} limit rows.')
